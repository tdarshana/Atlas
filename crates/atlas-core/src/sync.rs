    #[test]
    fn plan_apply_and_replan_is_unchanged() {
        let d = tempfile::tempdir().unwrap();
        std::fs::write(d.path().join("AGENTS.md"), "# Repo rules\n\nkeep\n").unwrap();
        std::fs::create_dir_all(d.path().join(".claude/agents")).unwrap();
        std::fs::write(d.path().join(".claude/agents/handwritten.md"), "---\nname: handwritten\n---\nmine\n").unwrap();
        let agents = vec![agent("reviewer"), agent("handwritten")];
        let inputs = SyncInputs {
            root: d.path(),
            agents: &agents,
            block: BlockContext { mcp_command: "atlas mcp".into(), agents: agents.clone(), practices: vec![], project_name: Some("p".into()) },
            targets: &[SyncKind::Claude, SyncKind::Codex, SyncKind::AgentsMd, SyncKind::ClaudeMd],
            home: d.path(),
            hooks: false,
            global: false,
            mirror_tasks_md: false,
            board_stages: &[],
            board_tasks: &[],
        };
        let ops = plan_sync(&inputs).unwrap();
        assert!(ops.iter().any(|o| o.kind == SyncKind::Claude && o.path.ends_with("reviewer.md") && o.action == SyncAction::Create));
        assert!(ops.iter().any(|o| o.path.ends_with("handwritten.md") && matches!(o.action, SyncAction::Skip(_))), "refuses to overwrite non-generated file");
        assert!(ops.iter().any(|o| o.kind == SyncKind::AgentsMd && o.action == SyncAction::Update));
        assert!(ops.iter().any(|o| o.kind == SyncKind::ClaudeMd && o.action == SyncAction::Create));
        let rep = apply(&ops).unwrap();
        assert_eq!(rep.skipped, 1);
        let agents_md = std::fs::read_to_string(d.path().join("AGENTS.md")).unwrap();
        assert!(agents_md.starts_with("# Repo rules\n\nkeep\n") && agents_md.contains("<!-- atlas:start -->"));
        assert_eq!(std::fs::read_to_string(d.path().join(".claude/agents/handwritten.md")).unwrap(), "---\nname: handwritten\n---\nmine\n");
        let again = plan_sync(&inputs).unwrap();
        assert!(again.iter().filter(|o| !matches!(o.action, SyncAction::Skip(_))).all(|o| o.action == SyncAction::Unchanged));
    }

    /// A practice body carrying the end marker used to close the block early, so the
